"""Exports for the code-aware Claude that works in the Bookkr repo (TRACKER R12).

Two files per export, both built from the issue register:

1. Friction log (JSONL): every friction occurrence ever found, one line each, with its category, issue, bucket,
   owner and the evidence from the chat. Cumulative: occurrences found since the previous export are marked new.
2. Investigation brief (Markdown): Bucket › Category › Issue, with counts, the component that made the first wrong
   decision, where that component lives in the code (from config/bookkr_architecture.md) and representative chat
   evidence. It states what happened, NOT what to change: no recommended fixes, lessons or guidance, so the agent
   reaches its own conclusions from the code.

Nothing here calls an LLM; an export costs no tokens.
"""
from __future__ import annotations

import json
import re
from datetime import datetime, timezone

from ..config import PROJECT_ROOT
from . import taxonomy as TX
from .issues import THEMES, journey_filter
from .store import conn, now_iso, save_export_file

ARCH_FILE = PROJECT_ROOT / "config" / "bookkr_architecture.md"
CLOSED = ("fixed", "wont_fix", "not_issue")
BUCKET_ORDER = ["technical", "intent", "suggestion"]
EXAMPLES_PER_ISSUE = 2

LOG_DDL = """CREATE TABLE IF NOT EXISTS investigation_exports (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at TEXT NOT NULL,
  created_by TEXT,
  max_item_id BIGINT,                -- occurrences with a higher id are "new" in the next export
  occurrences INTEGER,
  issues INTEGER,
  files TEXT                         -- JSON {"log": name, "brief": name}
)"""


def _ensure(c) -> None:
    c.execute(LOG_DDL)
    # which journey / buckets the export covered: "new since the last export" compares exports of the same scope
    c.execute("ALTER TABLE investigation_exports ADD COLUMN IF NOT EXISTS scope TEXT")


def _scope(journey: str | None, buckets: list[str] | None) -> str:
    return f"{journey or 'all'}|{','.join(sorted(buckets)) if buckets else 'all'}"


# Architecture pointers ------------------------------------------------------------------------------------------

def architecture_sections() -> dict[str, str]:
    """config/bookkr_architecture.md split by `## key` headings (owner keys, plus overview / flows)."""
    if not ARCH_FILE.is_file():
        return {}
    text = ARCH_FILE.read_text(encoding="utf-8")
    out, key, buf = {}, None, []
    for line in text.splitlines():
        m = re.match(r"^##\s+([A-Za-z0-9_]+)\s*$", line)
        if m:
            if key:
                out[key] = "\n".join(buf).strip()
            key, buf = m.group(1), []
        elif key:
            buf.append(line)
    if key:
        out[key] = "\n".join(buf).strip()
    return out


def code_paths(section: str) -> list[str]:
    """File paths mentioned in an architecture section (bookkrapp/..., bookkrapp-ui/..., bookkrapp-mobile/...)."""
    seen = []
    for p in re.findall(r"`?((?:bookkrapp(?:-ui|-mobile)?|docs|qa)/[\w./\-\[\]]+)`?", section or ""):
        p = p.rstrip(".,)")
        if p not in seen:
            seen.append(p)
    return seen[:8]


# Evidence ------------------------------------------------------------------------------------------------------

def _evidence(transcript, turns: list[int], max_lines: int = 6) -> list[str]:
    """The turns an occurrence points at, plus the user turn before the first one, as short lines."""
    if isinstance(transcript, str):
        try:
            transcript = json.loads(transcript)
        except ValueError:
            return []
    if not isinstance(transcript, list) or not turns:
        return []
    by_t = {t.get("t"): t for t in transcript if isinstance(t, dict)}
    want = sorted(set(turns))
    first = want[0]
    prev_user = next((n for n in range(first - 1, 0, -1) if by_t.get(n, {}).get("role") == "USER"), None)
    if prev_user:
        want = [prev_user] + want
    lines = []
    for n in want:
        t = by_t.get(n)
        if not t:
            continue
        body = (t.get("text") or "").strip().replace("\n", " ")
        if t.get("card"):
            body = (body + " " + t["card"]).strip()
        lines.append(f"[t{n}] {t.get('role')}: {body[:300]}")
        for e in (t.get("events") or [])[:4]:
            lines.append(f"      · {str(e.get('text') or '')[:240]}")
        if len(lines) >= max_lines:
            break
    return lines[:max_lines]


# Building -------------------------------------------------------------------------------------------------------

def _rows(journey: str | None, buckets: list[str] | None):
    jf, jp = journey_filter(journey)
    bf = f"AND i.bucket IN ({','.join('?' * len(buckets))})" if buckets else ""
    with conn() as c:
        _ensure(c)
        last = c.execute("SELECT max_item_id, created_at FROM investigation_exports WHERE scope = ? ORDER BY id DESC LIMIT 1",
                         (_scope(journey, buckets),)).fetchone()
        items = [dict(r) for r in c.execute(f"""
            SELECT i.id, i.issue_id, i.session_id, i.type, i.severity, i.bucket, i.owner, i.fix_lane, i.turns,
                   i.user_quote, i.what_went_wrong, i.why_friction, i.expected_interpretation, i.confidence,
                   i.source, i.verdict, i.served_model,
                   f.day, f.flow, f.outcome, f.title AS chat_title, f.user_id, f.transcript
            FROM items i JOIN findings f ON f.id = i.finding_id
            WHERE i.verdict <> 'not_friction' AND i.source = 'llm' {jf} {bf}
            ORDER BY i.id""", (*jp, *(buckets or []))).fetchall()]
        issues = {r["id"]: dict(r) for r in c.execute("SELECT * FROM issues WHERE merged_into IS NULL").fetchall()}
    return items, issues, (last[0] if last else None), (last[1] if last else None)


def build(journey: str | None = None, buckets: list[str] | None = None, include_closed: bool = False,
          created_by: str | None = None) -> dict:
    items, issues, last_max, last_at = _rows(journey, buckets)
    # occurrences of issues a reviewer marked "Not an issue" are false positives: never exported
    items = [it for it in items if (issues.get(it["issue_id"]) or {}).get("status") != "not_issue"]
    arch = architecture_sections()
    stamp = datetime.now(timezone.utc).strftime("%Y%m%d-%H%M%S")
    suffix = f"{'-' + journey if journey else ''}{'-' + '-'.join(buckets) if buckets else ''}"

    # 1. friction log: every occurrence
    log_lines = []
    for it in items:
        s = issues.get(it["issue_id"]) or {}
        turns = json.loads(it["turns"]) if isinstance(it["turns"], str) and it["turns"] else (it["turns"] or [])
        log_lines.append(json.dumps({
            "occurrence_id": it["id"], "new_since_last_export": bool(last_max is None or it["id"] > last_max),
            "day": it["day"], "chat_id": it["session_id"], "chat_title": it["chat_title"], "flow": it["flow"],
            "chat_outcome": it["outcome"], "bucket": it["bucket"], "category": s.get("theme") or "Other",
            "issue_id": it["issue_id"], "issue_title": s.get("title"), "issue_status": s.get("status"),
            "type": it["type"], "severity": it["severity"], "component": it["owner"],
            "component_label": TX.OWNER_LABEL.get(it["owner"], it["owner"]), "fix_lane": it["fix_lane"],
            "served_by_model": it["served_model"], "judge_confidence": it["confidence"],
            "reviewer_verdict": it["verdict"], "user_said": it["user_quote"], "what_happened": it["what_went_wrong"],
            "why_it_cost_the_user": it["why_friction"],
            "what_the_user_meant": it["expected_interpretation"] if it["bucket"] == "intent" else "",
            "evidence": _evidence(it["transcript"], turns),
        }, ensure_ascii=False))

    # 2. investigation brief: Bucket › Category › Issue
    by_issue: dict[int, list[dict]] = {}
    for it in items:
        if it["issue_id"]:
            by_issue.setdefault(it["issue_id"], []).append(it)
    tree: dict[str, dict[str, list[tuple[dict, list[dict]]]]] = {}
    for iid, occ in by_issue.items():
        s = issues.get(iid)
        if not s or (s["status"] in CLOSED and not include_closed):
            continue
        tree.setdefault(s["bucket"] or "intent", {}).setdefault(s.get("theme") or "Other", []).append((s, occ))
    n_issues = sum(len(v) for cats in tree.values() for v in cats.values())
    new_total = sum(1 for it in items if last_max is None or it["id"] > last_max)
    md = [
        "# Bookkr friction: investigation brief",
        "",
        f"Generated {now_iso()} by Bookr Analyst from production chats (PII-masked). "
        f"{n_issues} open issues, {len(items)} occurrences{' in ' + journey + ' journeys' if journey else ''}"
        f"{', ' + str(new_total) + ' new since the previous export (' + last_at[:10] + ')' if last_at else ''}.",
        "",
        "## How to use this",
        "You have the Bookkr codebase. Each issue below is a pattern an automated judge found in real user chats, grouped",
        "by root cause. For each one: find where it happens in the code, confirm or reject the judge's reading of which",
        "component made the first wrong decision, and explain the actual cause. The judge saw the chats and the stored",
        "intents, searches, LLM-call errors, app events and booking outcomes, but NOT the code, so its component guess can",
        "be wrong (especially for wrong-flow and technical issues). This brief describes what happened; it deliberately",
        "contains no suggested fixes.",
        "",
        "Hierarchy: Bucket (technical = the system broke · intent = Bookkr misread the user · suggestion = understood but",
        "offered something poor) › Category (product area) › Issue (one root cause) › occurrences (chats).",
        "The full list of occurrences is in the matching friction-log JSONL file, keyed by issue_id.",
        "",
    ]
    for b in BUCKET_ORDER + [x for x in tree if x not in BUCKET_ORDER]:
        cats = tree.get(b)
        if not cats:
            continue
        md += [f"# {TX.BUCKET_LABEL.get(b, b)}", "", TX.BUCKETS.get(b, ""), ""]
        order = sorted(cats, key=lambda k: (THEMES.index(k) if k in THEMES else 99, k))
        for cat in order:
            lst = sorted(cats[cat], key=lambda x: -len({o["session_id"] for o in x[1]}))
            once = [(s, occ) for s, occ in lst if len({o["session_id"] for o in occ}) == 1]
            lst = [x for x in lst if x not in once]
            md += [f"## {cat}", ""]
            for s, occ in lst:
                chats = len({o["session_id"] for o in occ})
                users = len({o["user_id"] or o["session_id"] for o in occ})
                days = sorted(o["day"] for o in occ)
                new = sum(1 for o in occ if last_max is None or o["id"] > last_max)
                sev = {"high": 0, "medium": 0, "low": 0}
                for o in occ:
                    sev[o["severity"]] = sev.get(o["severity"], 0) + 1
                owner = s.get("owner") or "unknown"
                md += [f"### Issue #{s['id']}: {s['title']}", "",
                       f"- **Seen in:** {chats} chats, {users} users, {days[0]} to {days[-1]}"
                       f"{f' ({new} new since the previous export)' if new and last_at else ''}",
                       f"- **Severity:** {sev['high']} high, {sev['medium']} medium, {sev['low']} low"
                       f" · **Status:** {s['status']}",
                       f"- **Component the judge blamed:** `{owner}` ({TX.OWNER_LABEL.get(owner, owner)})"]
                paths = code_paths(arch.get(owner, ""))
                if paths:
                    md.append(f"- **Where that component lives (UAT snapshot):** {', '.join(f'`{p}`' for p in paths)}")
                models = sorted({o["served_model"] for o in occ if o["served_model"]})
                if models:
                    md.append(f"- **Model that served the turn:** {', '.join(models[:3])}")
                if s.get("description"):
                    md += ["", s["description"]]
                md += ["", "**Examples**", ""]
                for o in sorted(occ, key=lambda o: ({"high": 0, "medium": 1, "low": 2}.get(o["severity"], 3), -o["id"]))[:EXAMPLES_PER_ISSUE]:
                    turns = json.loads(o["turns"]) if isinstance(o["turns"], str) and o["turns"] else (o["turns"] or [])
                    md.append(f"- Chat `{o['session_id']}` ({o['day']}, flow {o['flow'] or '-'}, ended: {o['outcome'] or '-'}): "
                              f"{o['what_went_wrong']}")
                    if o["user_quote"]:
                        md.append(f"  - User said: \"{o['user_quote'][:200]}\"")
                    if o["bucket"] == "intent" and o["expected_interpretation"]:
                        md.append(f"  - What the user meant (judge's reading): `{o['expected_interpretation'][:300]}`")
                    ev = _evidence(o["transcript"], turns)
                    if ev:
                        md += ["  ```", *[f"  {x}" for x in ev], "  ```"]
                md.append("")
            if once:
                md += ["**Seen in one chat so far** (details and evidence in the friction log):", ""]
                md += [f"- Issue #{s['id']}: {s['title']} · `{s.get('owner') or 'unknown'}` · chat `{occ[0]['session_id']}` ({occ[0]['day']})"
                       for s, occ in once]
                md.append("")
    ungrouped = [it for it in items if not it["issue_id"]]
    if ungrouped:
        md += ["# Not yet grouped into an issue", "",
               f"{len(ungrouped)} occurrences are judged but not grouped yet; they are in the friction log with issue_id null.", ""]

    log_name = f"bookkr_friction_log{suffix}_{stamp}.jsonl"
    brief_name = f"bookkr_investigation_brief{suffix}_{stamp}.md"
    save_export_file(log_name, "\n".join(log_lines) + ("\n" if log_lines else ""))
    save_export_file(brief_name, "\n".join(md) + "\n")
    with conn() as c:
        _ensure(c)
        c.execute("""INSERT INTO investigation_exports (created_at, created_by, max_item_id, occurrences, issues, files, scope)
                     VALUES (?,?,?,?,?,?,?)""",
                  (now_iso(), created_by, max((it["id"] for it in items), default=last_max), len(items), n_issues,
                   json.dumps({"log": log_name, "brief": brief_name}), _scope(journey, buckets)))
    return {"log": log_name, "brief": brief_name, "occurrences": len(items), "new_occurrences": new_total,
            "issues": n_issues, "ungrouped": len(ungrouped), "architecture_brief": bool(arch)}


def preview(journey: str | None = None) -> dict:
    items, issues, last_max, last_at = _rows(journey, None)
    items = [it for it in items if (issues.get(it["issue_id"]) or {}).get("status") != "not_issue"]
    open_ids = {i for i, s in issues.items() if s["status"] not in CLOSED}
    by_bucket: dict[str, int] = {}
    for it in items:
        by_bucket[it["bucket"]] = by_bucket.get(it["bucket"], 0) + 1
    with conn() as c:
        _ensure(c)
        past = [dict(r) for r in c.execute("""SELECT id, created_at, occurrences, issues, files, scope FROM investigation_exports
                                              ORDER BY id DESC LIMIT 10""").fetchall()]
    for p in past:
        p["files"] = json.loads(p["files"]) if p["files"] else {}
    return {"occurrences": len(items), "new_occurrences": sum(1 for it in items if last_max is None or it["id"] > last_max),
            "open_issues": len({it["issue_id"] for it in items if it["issue_id"] in open_ids}),
            "ungrouped": sum(1 for it in items if not it["issue_id"]), "by_bucket": by_bucket,
            "categories": len({(issues.get(it["issue_id"]) or {}).get("theme") or "Other" for it in items if it["issue_id"]}),
            "last_export": last_at, "architecture_brief": ARCH_FILE.is_file(), "past": past}
