class Row(tuple):
    """A result row readable by position (r[0]) and by column name (r["day"]); dict(r) gives a plain dict."""

    def __new__(cls, values, names):
        self = super().__new__(cls, values)
        self._names = names
        return self

    def keys(self):
        return list(self._names)

    def __getitem__(self, key):
        if isinstance(key, str):
            return tuple.__getitem__(self, self._names.index(key))
        return tuple.__getitem__(self, key)


def _row_factory(cursor):
    names = [c.name for c in cursor.description] if cursor.description else []
    return lambda values: Row(values, names)


_ready = False
_ready_lock = threading.Lock()


def _ensure_schema() -> None:
    """Create the schema and tables on first use (safe to run from several machines)."""
    global _ready
    if _ready:
        return
    with _ready_lock:
        if _ready:
            return
        with session("public") as pg:
            pg.execute("SELECT pg_advisory_xact_lock(4815162343)")
            pg.execute(f"CREATE SCHEMA IF NOT EXISTS {FRICTION_SCHEMA}")
            pg.execute(f"SET LOCAL search_path TO {FRICTION_SCHEMA}")
            pg.execute(SCHEMA)
            _backfill(Con(pg, _row_factory))
        _ready = True


def _backfill(c: Con) -> None:
    """Items stored before R8: bucket and owner from the type, then the lane."""
    from . import taxonomy as TX
    for r in c.execute("SELECT id, type, bucket, owner, served_model, lesson_is_rule FROM items WHERE fix_lane IS NULL").fetchall():
        t = TX.normalize_type(r["type"])
        b = r["bucket"] or TX.bucket_for(t)
        o = TX.normalize_owner(r["owner"] or TX.DEFAULT_OWNER.get(t))
        c.execute("UPDATE items SET type = ?, bucket = ?, owner = ?, fix_lane = ? WHERE id = ?",
                  (t, b, o, TX.fix_lane(b, o, r["served_model"], bool(r["lesson_is_rule"])), r["id"]))


def now_iso() -> str:
    return datetime.now(timezone.utc).replace(microsecond=0).isoformat()


@contextmanager
def conn():
    """One transaction on the friction schema: committed when the block ends, rolled back if it raises."""
    global _ready
    entered = False
    for attempt in (0, 1):
        _ensure_schema()
        try:
            with session(FRICTION_SCHEMA, "runs") as pg:
                entered = True
                yield Con(pg, _row_factory)
            return
        except FileNotFoundError:
            # the schema was archived by `--reset` on another machine since this process started: recreate it
            if entered or attempt:
                raise
            _ready = False


def save_export_file(name: str, content: str) -> None:
    with conn() as c:
        c.execute("""INSERT INTO export_files (name, content, created_at) VALUES (?, ?, ?)
                     ON CONFLICT (name) DO UPDATE SET content = EXCLUDED.content""", (name, content, now_iso()))


def load_export_file(name: str) -> str | None:
    with conn() as c:
        r = c.execute("SELECT content FROM export_files WHERE name = ?", (name,)).fetchone()
    return r[0] if r else None


JSON_FIELDS = {"signals", "transcript", "turns", "files", "counts", "content", "stats"}


def as_dict(row: Row | None) -> dict | None:
    if row is None:
        return None
    d = dict(row)
    for k in JSON_FIELDS & d.keys():
        if d[k]:
            try:
                d[k] = json.loads(d[k])
            except ValueError:
                pass
    return d


def all_dicts(rows) -> list[dict]:
    return [as_dict(r) for r in rows]
